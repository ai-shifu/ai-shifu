"""Refresh only initial teaching constraints with independent host provenance."""

from __future__ import annotations

import hashlib
from dataclasses import replace
from typing import TYPE_CHECKING

from markdownflow.engine.memory_context import parse_initial_memory_prompt
from markdownflow.engine.script import render_script_documents
from pydantic_ai.messages import ModelRequest, UserPromptPart

if TYPE_CHECKING:
    from markdownflow.engine import ScriptBundle, Session

INITIAL_TEACHING_BRIEF_KEY = "ai_shifu_initial_teaching_brief"


def _digest(content: str) -> str:
    """Identify the exact owned prefix without duplicating lesson content in metadata."""
    return hashlib.sha256(content.encode()).hexdigest()


def _provenance(script: str, constraints: str, part_index: int) -> dict[str, object]:
    """Describe host-owned ranges relative to the script after the mutable memory block."""
    return {
        "version": 1,
        "part_index": part_index,
        "script_length": len(script),
        "constraints_length": len(constraints),
        "prefix_sha256": _digest(script + constraints),
    }


def _constraint_document(brief: str | None) -> str:
    """Render exactly the optional constraints document emitted by the engine."""
    return f"\n\n<constraints>\n{brief}\n</constraints>" if brief else ""


def record_initial_teaching_brief(session: Session, bundle: ScriptBundle) -> bool:
    """Mark a prompt just generated by the current host, never a loaded legacy prompt.

    Call only after an observed fresh engine turn or an explicit host document
    rebuild. The trusted producer supplies the bundle it actually rendered.
    """
    for index, message in enumerate(session.messages):
        if not isinstance(message, ModelRequest):
            continue
        for part_index, part in enumerate(message.parts):
            if not isinstance(part, UserPromptPart):
                continue
            parsed = (
                parse_initial_memory_prompt(part.content)
                if isinstance(part.content, str)
                else None
            )
            if parsed is None or not part.content.startswith(
                render_script_documents(bundle), parsed.script_start
            ):
                return False
            metadata = {
                **(message.metadata or {}),
                INITIAL_TEACHING_BRIEF_KEY: _provenance(
                    f"<script>\n{bundle.script}\n</script>",
                    _constraint_document(bundle.constraints),
                    part_index,
                ),
            }
            if metadata != message.metadata:
                session.messages[index] = replace(message, metadata=metadata)
            return True
    return False


def refresh_teaching_brief(session: Session, brief: str) -> None:
    """Refresh proven host constraints; preserve all unmarked historical messages.

    Legacy hosts could update the bundle independently from the first message.
    Matching its constraint text, tags or extras cannot establish ownership.
    """
    session.script = replace(session.script, constraints=brief or None)
    for index, message in enumerate(session.messages):
        if not isinstance(message, ModelRequest):
            continue
        for part_index, part in enumerate(message.parts):
            if not isinstance(part, UserPromptPart):
                continue
            marker = (message.metadata or {}).get(INITIAL_TEACHING_BRIEF_KEY)
            if not isinstance(marker, dict) or not isinstance(part.content, str):
                return
            if (
                type(marker.get("version")) is not int
                or marker["version"] != 1
                or type(marker.get("part_index")) is not int
                or marker["part_index"] != part_index
                or type(marker.get("script_length")) is not int
                or marker["script_length"] <= 0
                or type(marker.get("constraints_length")) is not int
                or marker["constraints_length"] < 0
            ):
                return
            parsed = parse_initial_memory_prompt(part.content)
            if parsed is None:
                return
            script_end = parsed.script_start + marker["script_length"]
            owned_end = script_end + marker["constraints_length"]
            owned = part.content[parsed.script_start : owned_end]
            if owned_end > len(part.content) or _digest(owned) != marker.get(
                "prefix_sha256"
            ):
                return
            script = part.content[parsed.script_start : script_end]
            constraints = _constraint_document(brief)
            content = part.content[:script_end] + constraints + part.content[owned_end:]
            if content != part.content:
                parts = list(message.parts)
                parts[part_index] = replace(part, content=content)
                metadata = {
                    **(message.metadata or {}),
                    INITIAL_TEACHING_BRIEF_KEY: _provenance(
                        script, constraints, part_index
                    ),
                }
                session.messages[index] = replace(
                    message, parts=parts, metadata=metadata
                )
            return
